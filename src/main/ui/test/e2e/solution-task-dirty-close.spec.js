import { expect, test } from "@playwright/test";

test("dirty solution task close requires confirmation", async ({ page }) => {
  const soeid = `solkeys${Date.now()}`.slice(0, 20);
  expect((await page.request.post("/project-manager/api/auth/register", { data: { soeid, display_name: "Keyboard User", password: "Password123" } })).ok()).toBeTruthy();
  const personal = await page.request.post("/project-manager/api/spaces/personal", { data: {} });
  expect(personal.ok()).toBeTruthy();
  expect((await page.request.post("/project-manager/api/auth/active-space", { data: { space_id: (await personal.json()).space_id } })).ok()).toBeTruthy();
  const program = await page.request.post("/project-manager/api/programs", { data: { program_name: "Keyboard Program" } });
  expect(program.ok()).toBeTruthy();
  const programId = (await program.json()).program_id;
  const project = await page.request.post("/project-manager/api/projects", { data: { program_id: programId, project_name: "Keyboard Project" } });
  expect(project.ok()).toBeTruthy();
  const solution = await page.request.post(`/project-manager/api/projects/${(await project.json()).project_id}/solutions`, { data: { solution_name: "Keyboard Solution", version: "1.0" } });
  expect(solution.ok()).toBeTruthy();
  const solutionId = (await solution.json()).solution_id;
  const task = await page.request.post(`/project-manager/api/solutions/${solutionId}/tasks`, { data: { task_name: "Keyboard Task" } });
  expect(task.ok()).toBeTruthy();
  await page.goto("/project-manager/");
  await page.locator(`[data-action="edit"][data-type="solution"][data-id="${solutionId}"]`).first().click();
  await page.locator('#solution-modal [data-tab="tasks"]').click();
  const table = page.locator("#solution-task-table");
  await table.getByRole("button", { name: "Edit task Keyboard Task" }).click();
  const name = page.locator('#task-form [name="task_name"]');
  await expect(name).toHaveValue("Keyboard Task");
  await name.fill("Unsaved task edit");
  await page.keyboard.press("Escape");
  await expect(page.locator("#confirm-modal")).toBeVisible();
  await expect(page.locator("#confirm-modal-confirm")).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(page.locator("#confirm-modal-close")).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(page.locator("#confirm-modal-confirm")).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(page.locator("#confirm-modal-cancel")).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(name).toBeFocused();
  await expect(name).toHaveValue("Unsaved task edit");
  await expect(page.locator("#task-form")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.locator("#confirm-modal")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.locator("#confirm-modal")).toBeHidden();
  await expect(page.locator("#task-form")).toBeVisible();
  await expect(name).toHaveValue("Unsaved task edit");
  await page.keyboard.press("Escape");
  await expect(page.locator("#confirm-modal")).toBeVisible();
  await page.locator("#confirm-modal-confirm").click();
  await expect(page.locator("#task-form")).toBeHidden();
  await table.getByRole("button", { name: "Edit task Keyboard Task" }).click();
  await name.fill("Tab draft");
  await page.locator('#solution-modal [data-tab="details"]').click();
  await expect(page.locator("#confirm-modal")).toBeVisible();
  await page.locator("#confirm-modal-cancel").click();
  await expect(name).toHaveValue("Tab draft");
  await expect(page.locator('#solution-modal [data-tab="tasks"]')).toHaveClass(/active/);
  await page.locator('#solution-modal [data-tab="details"]').click();
  await page.locator("#confirm-modal-confirm").click();
  await expect(page.locator("#task-form")).toBeHidden();
  await expect(page.locator('#solution-modal [data-tab="details"]')).toHaveClass(/active/);
});
