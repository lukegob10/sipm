import { expect, test } from '@playwright/test';

test('old Kanban move cannot alter or focus a replacement session', async ({ page }) => {
  const soeid = `kb${Date.now().toString(36)}${Math.random().toString(36).slice(2, 7)}`;
  expect((await page.request.post('/project-manager/api/auth/register', { data: { soeid, display_name: 'Kanban user', password: 'Password123' } })).ok()).toBeTruthy();
  const personal = await page.request.post('/project-manager/api/spaces/personal', { data: {} });
  expect(personal.ok()).toBeTruthy();
  expect((await page.request.post('/project-manager/api/auth/active-space', { data: { space_id: (await personal.json()).space_id } })).ok()).toBeTruthy();
  const program = await page.request.post('/project-manager/api/programs', { data: { program_name: 'Kanban program' } });
  expect(program.ok()).toBeTruthy();
  const project = await page.request.post('/project-manager/api/projects', { data: { program_id: (await program.json()).program_id, project_name: 'Kanban project' } });
  expect(project.ok()).toBeTruthy();
  const phases = [{ phase_id: 'phase-a', phase_name: 'Phase A', sequence: 1 }, { phase_id: 'phase-b', phase_name: 'Phase B', sequence: 2 }];
  await page.route('**/api/phases', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(phases) }));
  const solutionResponse = await page.request.post(`/project-manager/api/projects/${(await project.json()).project_id}/solutions`, { data: { solution_name: 'Kanban item', version: '1' } });
  expect(solutionResponse.ok()).toBeTruthy();
  const solution = await solutionResponse.json();
  await page.goto('/project-manager/');
  await page.locator('.nav-btn[data-view="kanban"]').click();
  const select = page.locator(`[data-kanban-phase-select][data-solution-id="${solution.solution_id}"]`);
  await expect(select).toBeVisible();
  let markStarted;
  let release;
  let markCompleted;
  const completed = new Promise((resolve) => { markCompleted = resolve; });
  const started = new Promise((resolve) => { markStarted = resolve; });
  const held = new Promise((resolve) => { release = resolve; });
  await page.route(`**/api/solutions/${solution.solution_id}`, async (route) => {
    if (route.request().method() !== 'PATCH') return route.continue();
    markStarted();
    await held;
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ ...solution, solution_name: 'Old private response', current_phase: phases[1].phase_id }) });
    markCompleted();
  });
  await select.focus();
  await select.dispatchEvent('keydown', { key: 'ArrowDown' });
  const originalSelect = await select.elementHandle();
  expect((await page.request.post('/project-manager/api/programs', { data: { program_name: 'Refresh during phase selection' } })).ok()).toBeTruthy();
  await expect.poll(() => originalSelect.evaluate((node) => node.isConnected)).toBe(false);
  await expect(select).toBeFocused();
  await expect(select.locator('option[value="phase-b"]')).toHaveCount(1);

  await select.selectOption(phases[1].phase_id);
  await started;
  await page.locator('#logout-btn').dispatchEvent('click');
  await expect(page.locator('#auth-screen')).toBeVisible();
  await expect(page.locator('#kanban-board')).toBeEmpty();
  await page.locator('#login-form [name="soeid"]').fill(soeid);
  await page.locator('#login-form [name="password"]').fill('Password123');
  await page.locator('#login-form button[type="submit"]').click();
  await expect(page.locator('#app-shell')).toBeVisible();
  await page.locator('.nav-btn[data-view="kanban"]').click();
  await expect(select).toBeVisible();
  await page.evaluate(() => document.activeElement.blur());
  release();
  await completed;
  await page.waitForTimeout(300);
  await expect(page.locator('#kanban-board')).toContainText('Kanban item');
  await expect(page.locator('#kanban-board')).not.toContainText('Old private response');
  await expect(page.locator('#connection-status')).not.toContainText('moved to');
  expect(await page.evaluate(() => document.activeElement === document.body)).toBe(true);
});
