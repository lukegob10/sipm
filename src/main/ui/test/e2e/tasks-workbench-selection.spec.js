import { expect, test } from "@playwright/test";

test("task selection and sorting preserve keyboard focus and announce partial selection", async ({ page }) => {
  const soeid = `select${Date.now()}`.slice(0, 20);
  expect((await page.request.post("/project-manager/api/auth/register", { data: { soeid, display_name: "Selection Test", password: "Password123" } })).ok()).toBeTruthy();
  const personal = await page.request.post("/project-manager/api/spaces/personal", { data: {} });
  expect(personal.ok()).toBeTruthy();
  expect((await page.request.post("/project-manager/api/auth/active-space", { data: { space_id: (await personal.json()).space_id } })).ok()).toBeTruthy();
  const program = await page.request.post("/project-manager/api/programs", { data: { program_name: "Selection Program" } });
  expect(program.ok()).toBeTruthy();
  const project = await page.request.post("/project-manager/api/projects", { data: { program_id: (await program.json()).program_id, project_name: "Selection Project" } });
  expect(project.ok()).toBeTruthy();
  const solution = await page.request.post(`/project-manager/api/projects/${(await project.json()).project_id}/solutions`, { data: { solution_name: "Selection Solution", version: "1.0" } });
  expect(solution.ok()).toBeTruthy();
  const solutionId = (await solution.json()).solution_id;
  for (const task_name of ["Alpha task", "Beta task"]) {
    expect((await page.request.post(`/project-manager/api/solutions/${solutionId}/tasks`, { data: { task_name } })).ok()).toBeTruthy();
  }
  await page.goto("/project-manager/tasks-workbench");
  const table = page.locator("#tasks-workbench-table");
  const alpha = table.getByRole("checkbox", { name: "Select task Alpha task" });
  const all = table.getByRole("checkbox", { name: "Select all visible tasks" });
  await expect(alpha).toBeVisible();
  await alpha.focus();
  await page.keyboard.press("Space");
  await expect(alpha).toBeChecked();
  await expect(all).toHaveJSProperty("indeterminate", true);
  await expect(alpha).toBeFocused();
  await page.locator("#preferences-open").click();
  await expect(page.locator("#preferences-modal")).toBeVisible();
  await page.locator("#preferences-cancel").focus();
  await page.keyboard.press("Delete");
  await expect(page.locator("#confirm-modal")).toBeHidden();
  await page.keyboard.press("/");
  await expect(page.locator("#preferences-cancel")).toBeFocused();
  await page.locator("#preferences-cancel").click();
  await expect(alpha).toBeChecked();
  const sort = table.locator("[data-twb-task-sort]");
  await sort.focus();
  await page.keyboard.press("Enter");
  await expect(sort).toBeFocused();
  await expect(all).toHaveJSProperty("indeterminate", true);
  await all.focus();
  await page.keyboard.press("Space");
  await expect(all).toBeFocused();
  await expect(all).toBeChecked();
  await expect(all).toHaveJSProperty("indeterminate", false);
  await expect(table.getByRole("checkbox", { name: "Select task Beta task" })).toBeChecked();
  const edit = table.getByRole("button", { name: "Edit task Beta task" });
  await edit.focus();
  await page.keyboard.press("Enter");
  await expect(page.locator("#tasks-workbench-drawer")).toBeVisible();
  await expect(page.locator("#tasks-workbench-delete")).toBeEnabled();
  await page.locator("#tasks-workbench-delete").focus();
  await page.keyboard.press("Tab");
  await expect(page.locator("#tasks-workbench-reset")).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(page.locator("#tasks-workbench-delete")).toBeFocused();
  const title = page.locator('#tasks-workbench-form [name="task_name"]');
  await expect(title).toHaveValue("Beta task");
  await title.fill("Unsaved edit");
  await page.locator("#tasks-workbench-reset").click();
  await expect(title).toHaveValue("Beta task");
  await title.fill("Another unsaved edit");
  await page.locator("#tasks-workbench-reset").focus();
  await page.keyboard.press("Enter");
  await expect(title).toHaveValue("Beta task");
});
